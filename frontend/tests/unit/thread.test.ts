// Описание тестов и проверки
import { describe, expect, it } from "vitest";
// Функции расчёта лески
import { cumulativeLengthsM, pickSpool, rawLengthM, recommendedLines, spoolText, threadStats } from "@/lib/thread";

// Та же последовательность, что в backend/tests/test_thread.py — результаты обязаны совпадать.
// Последовательность: 0 → 120 → 0 → 30
const SEQ = [0, 120, 0, 30];

// Группа: длина лески
describe("длина лески", () => {
  // Две нити через центр круга 50 см — по 0,5 м
  it("две хорды через центр на 50 см = 1 м", () => {
    // Сумма 1 м с точностью до 10 знаков
    expect(rawLengthM(SEQ, 2, 50)).toBeCloseTo(1.0, 10);
  });

  // Накопленная длина только растёт и совпадает с суммой
  it("накопленная длина монотонна и сходится с суммой", () => {
    // Накопленные длины после каждого шага
    const cum = Array.from(cumulativeLengthsM(SEQ, 50));
    // До первого шага — ноль
    expect(cum[0]).toBe(0);
    // Отсортированный массив равен исходному — значит, он не убывает
    expect([...cum].sort((a, b) => a - b)).toEqual(cum);
    // После трёх шагов — та же длина, что считает rawLengthM
    expect(cum[3]).toBeCloseTo(rawLengthM(SEQ, 3, 50), 10);
  });

  // Запас 15 % по умолчанию
  it("запас по умолчанию 15 %", () => {
    // Расчёт для двух шагов
    const s = threadStats(SEQ, 2, 50);
    // Запас 0,15
    expect(s.margin).toBe(0.15);
    // округление до 0,1 м: 1,15 может стать 1,1 (Python) или 1,2 (JS) — оба допустимы
    // Итог около 1,15 м с допуском на округление
    expect(Math.abs(s.total_length_m - 1.15)).toBeLessThanOrEqual(0.05 + 1e-9);
  });

  // Шагов больше, чем в схеме, — ошибка
  it("steps за пределами последовательности — ошибка", () => {
    // Ждём RangeError
    expect(() => rawLengthM(SEQ, 4, 50)).toThrow(RangeError);
  });
});

// Группа: подбор катушки
describe("катушка", () => {
  // Таблица: длина → катушка → количество
  it.each([
    // Ноль — самая маленькая катушка
    [0, 100, 1],
    // Ровно 100 м
    [100, 100, 1],
    // Чуть больше — следующий размер
    [100.1, 150, 1],
    // Почти 1,2 км — катушка 1500
    [1176.7, 1500, 1],
    // Ровно 5 км — самая большая
    [5000, 5000, 1],
    // Больше 5 км — несколько катушек по 1000 м
    [5000.1, 1000, 6],
    // 12 345 м — 13 катушек
    [12345, 1000, 13],
  // Имя теста подставляет числа из таблицы
  ])("%f м → %i м × %i", (len, spool, count) => {
    // Подбор совпадает с ожиданием
    expect(pickSpool(len)).toEqual({ spool, count });
  });

  // На любую длину катушек хватает
  it("катушки всегда хватает", () => {
    // Перебираем длины от 0 до 20 км с шагом 37 м
    for (let len = 0; len < 20000; len += 37) {
      // Подбираем
      const { spool, count } = pickSpool(len);
      // Общая длина не меньше нужной
      expect(spool * count).toBeGreaterThanOrEqual(len);
    }
  });

  // Отрицательная длина — ошибка
  it("отрицательная длина — ошибка", () => {
    // Ждём исключение
    expect(() => pickSpool(-1)).toThrow();
  });

  // Подпись катушки
  it("подпись катушки", () => {
    // Одна катушка — с пробелом между тысячами
    expect(spoolText({ spool_m: 1500, spool_count: 1 })).toBe("1 500 м");
    // Несколько — «6 × 1 000 м»
    expect(spoolText({ spool_m: 1000, spool_count: 6 })).toBe("6 × 1 000 м");
  });
});

// Группа: рекомендованное число нитей
describe("рекомендованное число линий", () => {
  // Таблица: диаметр → нити
  it.each([
    // Минимальный диаметр — минимум нитей
    [20, 1000],
    // 30 см
    [30, 1200],
    // 50 см
    [50, 2000],
    // 70 см
    [70, 2800],
    // Максимум — 5000
    [150, 5000],
  // Имя теста
  ])("%i см → %i", (d, lines) => {
    // Совпадает
    expect(recommendedLines(d)).toBe(lines);
  });
});
