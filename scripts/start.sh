#!/usr/bin/env bash
# Запуск «Нитеграфа» на macOS/Linux одной командой: ./scripts/start.sh
# Сам ставит зависимости при первом запуске и после обновлений, поднимает бэкенд (8000) и фронтенд (3000).
# Остановка — Ctrl+C.
# Строгий режим: -e — остановиться при ошибке, -u — ошибка при неизвестной переменной, pipefail — ошибки в конвейерах
set -euo pipefail
# Корень репозитория: папка скрипта + .., превращённая в абсолютный путь
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# Каким Python пользоваться (можно задать PYTHON=python3.12)
PY="${PYTHON:-python3}"

# Сообщение о шаге
echo "▶ Бэкенд: зависимости"
# Переходим в папку бэкенда
cd "$ROOT/backend"
# Если виртуального окружения ещё нет — создаём
[ -d .venv ] || "$PY" -m venv .venv
# Проверка shellcheck не может проследить этот файл — отключаем её предупреждение
# shellcheck disable=SC1091
# Активируем окружение: дальше python и pip — из .venv
source .venv/bin/activate
# Удаление фона ставится по умолчанию; отключить: WITH_BG=0 ./scripts/start.sh
# Если удаление фона не отключено
if [ "${WITH_BG:-1}" = "1" ]; then
  # Ставим всё вместе с удалением фона; если не вышло — блок в фигурных скобках
  pip install -q -r requirements-bg.txt || {
    # Предупреждаем
    echo "⚠ Удаление фона не установилось — приложение запустится без него"
    # И ставим только основное
    pip install -q -r requirements.txt
  }
# Удаление фона отключено
else
  # Только основные зависимости
  pip install -q -r requirements.txt
fi

# Сообщение о шаге
echo "▶ Фронтенд: зависимости"
# Папка фронтенда
cd "$ROOT/frontend"
# Ставим пакеты Node.js тихо
npm install --no-audit --no-fund --loglevel=error

# Снова в бэкенд
cd "$ROOT/backend"
# Запускаем бэкенд в фоне (&)
uvicorn app.main:app --port 8000 &
# Запоминаем номер процесса бэкенда
BACK=$!
# В папку фронтенда
cd "$ROOT/frontend"
# Запускаем фронтенд в фоне
npm run dev &
# Номер процесса фронтенда
FRONT=$!
# При Ctrl+C или сигнале остановки — завершаем оба процесса
trap 'kill $BACK $FRONT 2>/dev/null; exit 0' INT TERM

# Пустая строка для красоты
echo
# Подсказка, куда идти
echo "✔ Откройте http://localhost:3000   (остановить — Ctrl+C)"
# Ждём, пока работают фоновые процессы
wait
