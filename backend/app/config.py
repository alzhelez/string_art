FONTS_DIR = BASE_DIR / "assets" / "fonts"


# Номер версии программы — показывается в /api/config и нужен для проверки обновлений
def app_version() -> str:
    """Версия сборки: файл app/_version.txt пишет сборка .exe (GitHub Actions); иначе — «dev»."""
    # Файла может не быть (запуск из исходников) — тогда упадём в except
    try:
        # Читаем версию из файла; пустой файл тоже считаем «dev»
        return (BASE_DIR / "_version.txt").read_text(encoding="utf-8").strip() or "dev"
    # Файла нет или его нельзя прочитать
    except OSError:
        # Версия для разработки: проверка обновлений в этом случае не включается
        return "dev"


# Где лежит база данных SQLite с проектами
def db_path() -> Path:
    """Путь к SQLite. Переопределяется переменной STRINGART_DB (нужно тестам)."""
    # По умолчанию — backend/data/string_art.db рядом с кодом
    default = BASE_DIR.parent / "data" / "string_art.db"
    # Тесты и программа для Windows подставляют свой путь через переменную окружения
    return Path(os.environ.get("STRINGART_DB", default))
